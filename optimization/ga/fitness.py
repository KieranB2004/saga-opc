
"""
=================================================================================
AI ASSISTANCE DISCLOSURE - optimization/ga/fitness.py
=================================================================================
This file implements a composite fitness function for genetic algorithm-based
optical proximity correction (OPC).

The fitness function evaluates candidate mask performance using:
1. Aerial image intensity error.
2. Binary developed-pattern error.
3. Edge placement error (EPE).
4. Printed area error.

A lower fitness score indicates better agreement with the desired pattern.

=================================================================================
"""

import numpy as np

from scipy.ndimage import binary_erosion
from scipy.ndimage import distance_transform_edt

from config.config import CONFIG


# ================================================================================
# FITNESS CONFIGURATION
# ================================================================================

# Define the contribution of each error metric to the total fitness score.
AERIAL_IMAGE_WEIGHT = 0.20
BINARY_ERROR_WEIGHT = 0.20
EPE_WEIGHT = 0.40
AREA_ERROR_WEIGHT = 0.20

# Define the maximum acceptable edge placement error in nanometres.
EPE_TOLERANCE_NM = 10.0

# Limit the normalized EPE penalty.
MAX_EPE_PENALTY = 3.0


# ================================================================================
# FUNCTION: extract_boundary
# ================================================================================

def extract_boundary(
    binary_pattern: np.ndarray
) -> np.ndarray:

    """
    Extract the boundary pixels of a binary pattern.

    Parameters:
        binary_pattern (np.ndarray): Binary mask or developed pattern.

    Returns:
        np.ndarray: Boolean array identifying boundary pixels.
    """

    # Convert the input pattern into a binary Boolean array.
    binary_pattern = np.asarray(binary_pattern, dtype=bool)

    # Erode the pattern to remove one layer of boundary pixels.
    eroded_pattern = binary_erosion(
        binary_pattern,
        structure=np.ones((3, 3), dtype=bool),
        border_value=0
    )

    # Identify pixels belonging to the original pattern boundary.
    boundary = binary_pattern & ~eroded_pattern

    # Return the extracted boundary.
    return boundary


# ================================================================================
# FUNCTION: fitness
# ================================================================================

def fitness(
    target_pattern: np.ndarray,
    candidate_aerial_image: np.ndarray
) -> float:

    """
    Evaluate a candidate aerial image against the desired OPC pattern.

    The total fitness score combines aerial image error, binary pattern error,
    edge placement error, and printed area error.

    Lower fitness values indicate better candidate performance.

    Parameters:
        target_pattern (np.ndarray):
            Desired geometric pattern.

        candidate_aerial_image (np.ndarray):
            Aerial image generated by the candidate photomask.

    Returns:
        float:
            Composite fitness score.
    """

    # --------------------------------------------------------------------------
    # STEP 1: Validate and prepare the input arrays.
    # --------------------------------------------------------------------------

    # Convert the target pattern into a NumPy array.
    target_pattern = np.asarray(target_pattern, dtype=float)

    # Convert the candidate aerial image into a NumPy array.
    candidate_aerial_image = np.asarray(
        candidate_aerial_image,
        dtype=float
    )

    # Verify that both inputs are two-dimensional.
    if target_pattern.ndim != 2 or candidate_aerial_image.ndim != 2:
        raise ValueError(
            "Target pattern and candidate aerial image must both be 2D arrays."
        )

    # Verify that both arrays have matching dimensions.
    if target_pattern.shape != candidate_aerial_image.shape:
        raise ValueError(
            f"Target pattern shape {target_pattern.shape} does not match "
            f"candidate aerial image shape {candidate_aerial_image.shape}."
        )

    # Verify that both arrays contain finite values.
    if not np.all(np.isfinite(target_pattern)):
        raise ValueError("Target pattern contains non-finite values.")

    if not np.all(np.isfinite(candidate_aerial_image)):
        raise ValueError("Candidate aerial image contains non-finite values.")

    # Convert the geometric target into a binary pattern.
    target_pattern = target_pattern >= 0.5

    # Verify that the target pattern contains occupied pixels.
    if not np.any(target_pattern):
        raise ValueError("Target pattern contains no occupied pixels.")

    # --------------------------------------------------------------------------
    # STEP 2: Calculate the aerial image intensity error.
    # --------------------------------------------------------------------------

    # Restrict aerial image intensities to the expected normalized range.
    normalized_aerial_image = np.clip(
        candidate_aerial_image,
        0.0,
        1.0
    )

    # Calculate the mean squared difference between aerial intensity
    # and the desired binary pattern.
    aerial_image_error = np.mean(
        (target_pattern.astype(float) - normalized_aerial_image) ** 2
    )

    # --------------------------------------------------------------------------
    # STEP 3: Calculate the binary developed-pattern error.
    # --------------------------------------------------------------------------

    # Retrieve the printing threshold from the configuration.
    threshold = CONFIG["printing"]["default_intensity_threshold"]

    # Verify that the printing threshold is valid.
    if not 0.0 <= threshold <= 1.0:
        raise ValueError("Printing threshold must be between 0 and 1.")

    # Convert the candidate aerial image into a binary developed pattern.
    developed_pattern = candidate_aerial_image >= threshold

    # Calculate the fraction of pixels that differ from the target pattern.
    binary_error = np.mean(
        developed_pattern != target_pattern
    )

    # --------------------------------------------------------------------------
    # STEP 4: Calculate the intersection over union (IoU) error.
    # --------------------------------------------------------------------------

    # Calculate the intersection between the target and developed patterns.
    intersection = np.sum(
        target_pattern & developed_pattern
    )

    # Calculate the union between the target and developed patterns.
    union = np.sum(
        target_pattern | developed_pattern
    )

    # Calculate the intersection over union.
    iou = intersection / union if union > 0 else 0.0

    # Convert IoU into an error where zero represents a perfect match.
    iou_error = 1.0 - iou

    # --------------------------------------------------------------------------
    # STEP 5: Calculate the symmetric edge placement error.
    # --------------------------------------------------------------------------

    # Extract the target pattern boundary.
    target_boundary = extract_boundary(target_pattern)

    # Extract the developed pattern boundary.
    developed_boundary = extract_boundary(developed_pattern)

    # Retrieve the physical simulation grid resolution.
    px_per_um = CONFIG["optics"]["grid_resolution_px_per_um"]

    # Verify that the grid resolution is positive.
    if px_per_um <= 0:
        raise ValueError("Grid resolution must be greater than zero.")

    # Convert the grid resolution into physical pixel spacing in micrometres.
    pixel_size_um = 1.0 / px_per_um

    # Convert the EPE tolerance from nanometres into micrometres.
    epe_tolerance_um = EPE_TOLERANCE_NM / 1000.0

    # Check whether both patterns contain identifiable boundaries.
    if np.any(target_boundary) and np.any(developed_boundary):

        # Calculate the distance from every pixel to the nearest target boundary.
        distance_to_target = distance_transform_edt(
            ~target_boundary,
            sampling=pixel_size_um
        )

        # Calculate the distance from every pixel to the nearest developed boundary.
        distance_to_developed = distance_transform_edt(
            ~developed_boundary,
            sampling=pixel_size_um
        )

        # Calculate the average distance from developed edges to target edges.
        developed_to_target = np.mean(
            distance_to_target[developed_boundary]
        )

        # Calculate the average distance from target edges to developed edges.
        target_to_developed = np.mean(
            distance_to_developed[target_boundary]
        )

        # Calculate the symmetric average edge placement error.
        mean_epe_um = (
            developed_to_target + target_to_developed
        ) / 2.0

        # Normalize EPE using the specified physical tolerance.
        epe_error = mean_epe_um / epe_tolerance_um

        # Limit the maximum EPE contribution.
        epe_error = min(epe_error, MAX_EPE_PENALTY)

    else:

        # Penalize candidates that have no identifiable boundary.
        epe_error = MAX_EPE_PENALTY

    # --------------------------------------------------------------------------
    # STEP 6: Calculate the printed area error.
    # --------------------------------------------------------------------------

    # Calculate the number of occupied target pixels.
    target_area = np.sum(target_pattern)

    # Calculate the number of occupied developed pixels.
    developed_area = np.sum(developed_pattern)

    # Calculate the relative difference between target and developed areas.
    area_error = abs(
        target_area - developed_area
    ) / target_area

    # Limit the area error contribution.
    area_error = min(area_error, 1.0)

    # --------------------------------------------------------------------------
    # STEP 7: Calculate the composite fitness score.
    # --------------------------------------------------------------------------

    # Combine the individual error metrics using their respective weights.
    total_fitness = (
        AERIAL_IMAGE_WEIGHT * aerial_image_error
        + BINARY_ERROR_WEIGHT * binary_error
        + EPE_WEIGHT * epe_error
        + AREA_ERROR_WEIGHT * area_error
    )

    # Return the composite fitness score.
    return float(total_fitness)
